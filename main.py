import shutil
from pathlib import Path

from provided_code.monai_data import NPZDataSet
from provided_code.network_functions_MONAI import PredictionModel  # keeps the same API
from provided_code.utils_MONAI import get_paths,plot_validation_case
from provided_code.dose_evaluation_npz import DoseEvaluator

   
if __name__ == "__main__":

    model_name = "baseline"  # Name model to train and number of epochs to train it for
    test_time = False  # Only change this to True when the model has been fully tuned on the validation set
    num_epochs = 1  # This should probably be increased to 100-200 after your dry run

    # Define project directories
    primary_directory = Path().resolve()  # directory where everything is stored
    provided_data_dir = primary_directory / "provided-data"
    training_data_dir = provided_data_dir / "train-pats"
    validation_data_dir = provided_data_dir / "validation-pats"
    testing_data_dir = provided_data_dir / "test-pats"
    results_dir = primary_directory / "results"  # where any data generated by this code (e.g., predictions, models) are stored


    # Prepare the data
    training_plan_paths = get_paths(training_data_dir)  # gets the path of each plan's directory
    # Define hold out set
    hold_out_data_dir = validation_data_dir if test_time is False else testing_data_dir
    stage_name, _ = hold_out_data_dir.stem.split("-")
    hold_out_plan_paths = get_paths(hold_out_data_dir)

   
    # This is the complete handler class for the data 
    dataset = NPZDataSet(training_paths=training_plan_paths,validation_paths=hold_out_plan_paths)

    # Train a model
   
    data_loader_train = dataset.train_dataloader()

    dose_prediction_model_train = PredictionModel(
        data_loader_train, results_dir, model_name, "train",learning_rate=1e-3)
    
    dose_prediction_model_train.train_model(num_epochs, save_frequency=1, keep_model_history=1)



    # Predict dose for the held out set
    data_loader_hold_out = dataset.predict_dataloader()

    dose_prediction_model_hold_out = PredictionModel(
        data_loader_hold_out, results_dir, model_name=model_name, stage=stage_name)
    
    # Predict using the model saved at the last epoch with the same patch size as used in the tranform pipeline
    dose_prediction_model_hold_out.predict_dose(epoch=50,batch_size=4, roi_size=dataset.patch_size)

    # print out scores if data was left for a hold out set
    
    prediction_dir = results_dir / model_name / f"{stage_name}-predictions"
    dose_evaluator = DoseEvaluator(hold_out_plan_paths, prediction_dir)


    if not test_time:
        dose_evaluator.evaluate()
        dose_score, dvh_score = dose_evaluator.get_scores()
        print(f"For this out-of-sample test on {stage_name}:\n\tthe DVH score is {dvh_score:.3f}\n\tthe dose score is {dose_score:.3f}")
        plot_validation_case(
            patient_path=hold_out_plan_paths[0],
            prediction_dir=prediction_dir,
        )
    else:
        # Zip dose to submit
        submission_dir = results_dir / "submissions"
        submission_dir.mkdir(exist_ok=True)
        shutil.make_archive(str(submission_dir / model_name), "zip", dose_prediction_model_hold_out.prediction_dir)
